#!/usr/bin/env python3
"""P6e (experiment): painted upper-body states for the reference villager's rig walk.

The eight frames of the painted walk sheet (man-walk8) show the same villager with a differently painted upper body
in each phase: tunic hem, slit and folds, belt, shoulders and arms all change. This script cuts the upper body (head,
torso, tunic, both arms — everything above the trousers) out of each frame, registers the frames on the belt (the
pelvis the rig's legs hang from) and makes three in-betweens per interval by pushing the nearer painted frame along
the optical flow to its neighbour, so the upper body changes smoothly with the walk phase instead of jumping between
eight pictures.

Writes src/assets/sprites/folk/man-torso.webp (STATES cells side by side) and src/game/man-torso-data.ts.
Run from the repo root: python3 scripts/gen-man-torso.py
"""
import json

import cv2
import numpy as np
from PIL import Image
from scipy import ndimage as nd

SRC = "src/assets/sprites/folk/man-walk8.webp"
PER = 4  # states per painted interval → 32 states per walk cycle
im = np.array(Image.open(SRC).convert("RGBA")).astype(np.float32)
N = 8
W = im.shape[1] // N
H = im.shape[0]
yy, xx = np.mgrid[0:H, 0:W]

# ---- cut the upper body: warm (tunic, skin, belt) or above the waist, connected to the torso ----
ups, belts = [], []
for k in range(N):
    f = im[:, k * W:(k + 1) * W]
    r, b, a = f[..., 0], f[..., 2], f[..., 3]
    m = (a > 8) & (((r - b) > 52) | (yy < 120)) & (yy < 170)
    lab, _ = nd.label(m)
    seed = np.argwhere(lab[80:90] > 0)
    keep = np.bincount(lab[80:90][lab[80:90] > 0]).argmax()
    m = nd.binary_closing(lab == keep, iterations=1) & (a > 8)
    u = f.copy()
    u[~m] = 0
    ups.append(u)
    ys, xs = np.nonzero(u[100:108, :, 3] > 100)
    belts.append(xs.mean())

# ---- register on the belt of frame 0 (the frame the rig's body and legs are cut from) ----
PAD = 24
CW = W + 2 * PAD
reg = []
for k, u in enumerate(ups):
    dx = int(round(belts[0] - belts[k]))
    c = np.zeros((H, CW, 4), np.float32)
    c[:, PAD + dx:PAD + dx + W] = u
    reg.append(c)


def pm(c):
    d = c.copy()
    d[..., :3] *= d[..., 3:] / 255
    return d


def gray(c):
    a = c[..., 3:] / 255
    return (c[..., :3] * a).mean(-1).clip(0, 255).astype(np.uint8)  # on black: outlines carry the motion


def flow(a, b):
    # dense Farnebäck flow, wide window: follows the swinging forearm best of the tested methods (DIS left a ghost hand)
    return cv2.calcOpticalFlowFarneback(gray(a), gray(b), None, 0.5, 5, 21, 5, 7, 1.5, 0)


gy, gx = np.mgrid[0:H, 0:CW].astype(np.float32)


def warp(img, f, t):
    return cv2.remap(img, gx + f[..., 0] * t, gy + f[..., 1] * t, cv2.INTER_LINEAR, borderMode=cv2.BORDER_CONSTANT, borderValue=0)


states = []
for k in range(N):
    A, B = reg[k], reg[(k + 1) % N]
    fab = flow(A, B)
    fba = flow(B, A)
    for i in range(PER):
        t = i / PER
        if i == 0:
            states.append(A.copy())
            continue
        # each in-between is the nearer painted frame pushed along the flow (no cross-fade: a blend of two paintings
        # shows a double hem and a ghost hand; a single warped painting stays sharp)
        o = warp(pm(A), fab, -t) if t < 0.5 else warp(pm(B), fba, -(1 - t))
        al = o[..., 3:]
        o[..., :3] = np.where(al > 0, o[..., :3] * 255 / np.maximum(al, 1e-3), 0)
        o[o[..., 3] < 12] = 0  # the warp leaves a faint fringe where an edge moved: cut it
        states.append(o)

# ---- common crop and atlas ----
alpha = np.max([s[..., 3] for s in states], axis=0) > 8
ys, xs = np.nonzero(alpha)
y0, y1, x0, x1 = ys.min(), ys.max() + 1, xs.min(), xs.max() + 1
cw, ch = int(x1 - x0), int(y1 - y0)
atlas = np.concatenate([s[y0:y1, x0:x1] for s in states], axis=1).clip(0, 255).astype(np.uint8)
Image.fromarray(atlas, "RGBA").save("src/assets/sprites/folk/man-torso.webp", quality=88, alpha_quality=100, method=6)
# the state with the arms closest to the body (narrowest silhouette) stands in for standing and the slowest steps
widths = [int(np.ptp(np.nonzero((st[y0:y1, x0:x1, 3] > 100).any(0))[0])) for st in states]
data = {
    "states": len(states), "perFrame": PER, "cell": [cw, ch], "stand": int(np.argmin(widths)),
    # top-left of a state in the coordinates of man-walk8 frame 0 (the rig's source cell)
    "origin": [int(x0 - PAD), int(y0)],
}
with open("src/game/man-torso-data.ts", "w") as f:
    f.write("/** Generated by scripts/gen-man-torso.py from man-walk8 — upper-body states of the rig walk. Do not edit. */\n")
    f.write("export const MAN_TORSO = " + json.dumps(data, separators=(",", ":")) + " as const;\n")
print("states", len(states), "cell", cw, ch, "atlas", atlas.shape, "origin", data["origin"])
