"""P6c: prepares the supplied painted 12-frame walk (scripts/art/man-walk12-quelle.png, one figure per frame laid out
left to right on a transparent strip) as a game walk sheet in the same cell geometry as man-walk8: 240 px cells, ground
line at 236, figure 224 px tall, head centred in the cell. No repainting: cut, clean the background remnants, scale,
register. Writes src/assets/sprites/folk/man-walk12.webp and src/game/man-walk12-data.ts.
Run from the repo root: python3 scripts/gen-man-painted.py"""
import json
import numpy as np
from PIL import Image
from scipy import ndimage

SRC = "scripts/art/man-walk12-quelle.png"
CW, CH, GROUND, TOP, CX = 200, 240, 236, 12, 100
src = np.array(Image.open(SRC).convert("RGBA")).astype(np.float64)
H, W = src.shape[:2]
alpha = src[..., 3]
yy = np.arange(H)[:, None] * np.ones((1, W))

# 1) background remnants: light, unsaturated pixels below the hem that touch the transparent area (the generator's
#    ground strip along the bottom rows and the backdrop showing between the legs of the standing frame)
rgb = src[..., :3]
lum, sat = rgb.mean(-1), rgb.max(-1) - rgb.min(-1)
cand = (alpha > 0) & (lum > 168) & (sat < 42) & (yy > 236)
lab, n = ndimage.label(cand)
outside = ndimage.binary_dilation(alpha < 8, iterations=1)
touch = ndimage.maximum(outside, lab, range(1, n + 1)) if n else []
for i, t in enumerate(touch, 1):
    if t: alpha[lab == i] = 0
alpha[yy >= H - 2] = np.where((lum[yy >= H - 2] > 160), 0, alpha[yy >= H - 2])  # last rows: the ground strip
src[..., 3] = alpha

# 2) one figure per frame: the 12 large components, plus any small piece inside a figure's box
solid = alpha > 8
lab, n = ndimage.label(solid)
sizes = ndimage.sum(solid, lab, range(1, n + 1))
big = sorted([i + 1 for i, s in enumerate(sizes) if s > 2000], key=lambda i: np.where(lab == i)[1].min())
assert len(big) == 12, f"expected 12 figures, found {len(big)}"
boxes = [ndimage.find_objects((lab == i).astype(int))[0] for i in big]

s = (GROUND - TOP) / (H - 1 - 17)  # figure 17..325 in the source -> 12..236
sheet = Image.new("RGBA", (CW * 12, CH), (0, 0, 0, 0))
info = []
for k, i in enumerate(big):
    sl = boxes[k]
    x0, x1 = sl[1].start, sl[1].stop
    keep = np.zeros_like(solid)
    for j in range(1, n + 1):  # the figure and stray pieces whose bulk lies within its box
        if j == i or (sizes[j - 1] <= 2000 and x0 <= np.where(lab == j)[1].mean() < x1): keep |= lab == j
    keep = ndimage.binary_closing(keep, iterations=1) & (alpha > 0)
    ys, xs = np.where(keep)
    head = xs[(ys >= 17) & (ys < 75)].mean()
    # stance contact: front sole pixels on the ground rows (boots are dark)
    g = keep[H - 4:] & (lum[H - 4:] < 130)
    cols = np.where(g.any(0))[0]
    runs, a0, p = [], cols[0], cols[0]
    for x in cols[1:]:
        if x > p + 3: runs.append((a0, p)); a0 = x
        p = x
    runs.append((a0, p))
    fr = np.zeros((H, x1 - x0, 4))
    fr[..., :3] = src[:, x0:x1, :3]
    fr[..., 3] = np.where(keep[:, x0:x1], alpha[:, x0:x1], 0)
    # premultiplied resample keeps the dark rims away from the cut edge
    pm = fr.copy(); pm[..., :3] *= pm[..., 3:] / 255
    nw, nh = round((x1 - x0) * s), round(H * s)
    im = Image.fromarray(pm.clip(0, 255).astype(np.uint8), "RGBA").resize((nw, nh), Image.LANCZOS)
    a = np.array(im).astype(np.float64)
    al = a[..., 3:]
    a[..., :3] = np.where(al > 0, a[..., :3] * 255 / np.maximum(al, 1), 0)
    im = Image.fromarray(a.clip(0, 255).astype(np.uint8), "RGBA")
    ox = round(CX - (head - x0) * s)  # head centred, like the painted man sheets
    oy = round(GROUND - (H - 1) * s) + 1  # source ground row -> 236 (the resampled last row is soft)
    cell = Image.new("RGBA", (CW, CH), (0, 0, 0, 0))
    cell.alpha_composite(im, (max(0, ox), max(0, oy)), (max(0, -ox), max(0, -oy)))
    sheet.alpha_composite(cell, (k * CW, 0))
    front = runs[-1]
    ca = np.array(cell)[..., 3] > 100
    cy, cx = np.where(ca)
    info.append({"heel": round((front[0] - head) * s + CX, 1), "toe": round((front[1] - head) * s + CX, 1), "contacts": len(runs),
                 "head": round(float(cx[cy < cy.min() + 42].mean()), 1), "top": int(cy.min()), "bottom": int(cy.max())})
sheet.save("src/assets/sprites/folk/man-walk12.webp", quality=90, alpha_quality=100, method=6)  # like the other folk sheets
with open("src/game/man-walk12-data.ts", "w") as f:
    f.write("// generated by scripts/gen-man-painted.py: per frame the front sole's ground contact (cell px, head at x=100)\n")
    f.write("export const MAN_WALK12 = " + json.dumps({"cell": [CW, CH], "ground": GROUND, "frames": info}, separators=(",", ":")) + " as const;\n")
print("scale", round(s, 4)); [print(k, v) for k, v in enumerate(info)]
